#!/usr/bin/env python3
"""03-3 物体识别抓取: 像素→相机 3D 坐标公式验证

演示核心公式:
  X = (u - cx) × Z / fx
  Y = (v - cy) × Z / fy
  Z = 深度值（米）

用 D435 典型内参 + 测试数据验证公式正确性。
不需要相机——纯数值计算，帮助学生理解公式含义。
"""

# --- D435 典型内参 (640×480 分辨率) ---
fx, fy = 613.4, 612.2
cx, cy = 330.2, 240.6

print("=" * 60)
print("相机内参 (D435 典型值, 640×480):")
print(f"  fx={fx:.1f}  fy={fy:.1f}  cx={cx:.1f}  cy={cy:.1f}")
print()

# --- 测试场景: 物体在图像不同位置，距离 0.5m ---
test_cases = [
    # (描述,  u,   v,  Z)
    ("图像正中心",    320, 240, 0.5),
    ("中心偏右 100px", 420, 240, 0.5),
    ("中心偏下 100px", 320, 340, 0.5),
    ("右上角",        500, 100, 0.5),
    ("近处物体",      320, 240, 0.3),
    ("远处物体",      320, 240, 2.0),
]

print("测试: 不同像素位置 + 深度的 3D 坐标计算")
print("-" * 60)
print(f"{'场景':<16} {'像素(u,v)':<12} {'Z(m)':<8} {'X(m)':<10} {'Y(m)':<10}")
print("-" * 60)

for desc, u, v, Z in test_cases:
    X = (u - cx) * Z / fx
    Y = (v - cy) * Z / fy
    print(f"{desc:<16} ({u:>3},{v:>3})    {Z:<8.2f} {X:<10.3f} {Y:<10.3f}")

print()
print("=" * 60)
print("关键观察:")
print("  1. 像素偏离中心越多 → X/Y 越大（物体偏离光轴越远）")
print("  2. 深度 Z 越大 → 相同像素偏移对应更大的世界坐标")
print("  3. fx/fy 越大 → 相同像素偏移对应更小的世界坐标（长焦效果）")
print("  4. 中心点 (u=cx, v=cy) → X=0, Y=0（在光轴上）")
print()
print("⚠️ 公式的前提条件:")
print("  - 深度图已对齐到彩色图 (align_depth.enable:=true)")
print("  - 深度值 Z 已转为米 (D435 深度图 /1000)")
print("  - 相机坐标系: X=右, Y=下, Z=前")
